namespace Hexalith.Tenants.UI.Tests.Services.Gateways;

internal sealed class StatusHandler(string body, HttpStatusCode statusCode = HttpStatusCode.OK, Func<HttpRequestMessage, string>? bodyForRequest = null) : HttpMessageHandler
{
    public Uri? RequestUri { get; private set; }

    protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken)
    {
        RequestUri = request.RequestUri;
        return Task.FromResult(new HttpResponseMessage(statusCode)
        {
            Content = new StringContent(bodyForRequest?.Invoke(request) ?? body),
        });
    }
}
